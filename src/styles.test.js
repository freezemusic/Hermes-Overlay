function infiniteSelectors(source) {
  const found = [];
  const re = /([^{}@]+)\{([^{}]*)\}/g;
  let match = re.exec(source);
  while (match) {
    const body = match[2];
    if (/animation\s*:/.test(body) && /infinite/.test(body)) {
      found.push(match[1].trim());
    }
    match = re.exec(source);
  }
  return found;
}

